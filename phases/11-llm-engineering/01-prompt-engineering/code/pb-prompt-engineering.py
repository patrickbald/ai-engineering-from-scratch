# takes name of a prompt pattern and a dict of variables, fills in that patterns template, and returns a model agnostic request description
def build_prompt(pattern_name, variables, system_override=None):
    pattern = PROMPT_PATTERNS.get(pattern_name) # get checks dict for key value
    if not pattern:
        raise ValueError(f"unknown pattern: {pattern_name}. Available prompt patterns: {list(PROMPT_PATTERNS.keys())}")

    missing = [v for v in pattern["variables"] if v not in variables]
    if missing:
        raise ValueError(f"Missing variables for {pattern_name}: {missing}")

    rendered = pattern["template"].format(**variables) # ** unpacks a dict into keyword arguments
    system = system_override or f"You are an AI assistant using the {pattern["name"]}"

    return {
        "system": system,
        "user": rendered,
        "temperature": pattern['temperature'],
        "pattern": pattern_name,
        "metadata": {
            "description": pattern['description'],
            "variables_used": list(variables.keys())
        }
    }


